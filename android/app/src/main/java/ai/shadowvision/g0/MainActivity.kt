package ai.shadowvision.g0

import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.os.Bundle
import android.os.PowerManager
import android.os.SystemClock
import android.widget.Button
import android.widget.LinearLayout
import android.widget.ScrollView
import android.widget.TextView
import androidx.appcompat.app.AppCompatActivity
import androidx.lifecycle.lifecycleScope
import kotlinx.coroutines.launch
import java.io.File

/**
 * G0 harness UI. Deliberately ugly: it exists to produce numbers, and every
 * widget here maps to one gate criterion. It is NOT the product UI — the
 * product UI is the next milestone and must not be built before this passes.
 *
 * Workflow on a device:
 *   adb push test.ppm /data/local/tmp/g0/     (generated by sv_g0 --gen-test)
 *   (or drop a real photo + mask into /sdcard/Android/data/<pkg>/files/g0/)
 *   press "Run gate" and read the report.
 */
class MainActivity : AppCompatActivity() {

    private lateinit var log: TextView
    private var bitmap: Bitmap? = null
    private var mask: ByteArray? = null
    private var maskW = 0
    private var maskH = 0

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)

        log = TextView(this).apply {
            textSize = 11f
            typeface = android.graphics.Typeface.MONOSPACE
            setPadding(24, 24, 24, 24)
        }

        val run = Button(this).apply { text = getString(android.R.string.ok) + " — run gate" }
        val loadSynthetic = Button(this).apply { text = "load synthetic backend" }
        val root = LinearLayout(this).apply {
            orientation = LinearLayout.VERTICAL
            addView(loadSynthetic, LinearLayout.LayoutParams(-1, -2))
            addView(run, LinearLayout.LayoutParams(-1, -2))
            addView(ScrollView(this@MainActivity).apply { addView(log) },
                LinearLayout.LayoutParams(-1, 0, 1f))
        }
        setContentView(root)

        // Budget is a hard ceiling, not a hope: 1200 MB tracked.
        SvEngine.init(budgetMb = 1200)
        append("native ${SvEngine.version()}")

        loadSynthetic.setOnClickListener {
            val rc = SvEngine.loadModel(null, useNpu = false, threads = 2)
            append("loadModel(synthetic) -> $rc")
            loadTestImage()
        }

        run.setOnClickListener {
            val bmp = bitmap
            val m = mask
            if (bmp == null || m == null) {
                append("no image loaded")
                return@setOnClickListener
            }
            val pm = getSystemService(PowerManager::class.java)
            val thermalBefore = pm.currentThermalStatus
            val t0 = SystemClock.elapsedRealtime()
            lifecycleScope.launch {
                val report = SvEngine.inpaint(bmp, m, maskW, maskH, workResolution = 512,
                    thermal = thermalBefore)
                val wall = SystemClock.elapsedRealtime() - t0
                val thermalAfter = pm.currentThermalStatus
                append("")
                append("=== G0 ===")
                append(report.summary)
                append("wall clock   : $wall ms (includes JNI + bitmap copy)")
                append("tracked peak : %.1f MB / budget %.0f MB"
                    .format(report.trackedPeakMb, report.budgetMb))
                append("peak RSS     : %.1f MB".format(report.peakRssMb))
                append("thermal      : $thermalBefore -> $thermalAfter")
                append("work res     : 512")
                report.stages.forEach { append("  - %-18s %8.1f ms".format(it.name, it.ms)) }
                append("gate: ${if (report.ok && report.peakRssMb < 700) "PASS" else "FAIL"}")
            }
        }
    }

    /**
     * The device-side fixture is a generated pattern: we cannot ship a real
     * photo (licensing + size), and a synthetic edge-heavy pattern is a harder
     * seam test than a smooth photo anyway.
     */
    private fun loadTestImage() {
        val w = 1280
        val h = 960
        val bmp = Bitmap.createBitmap(w, h, Bitmap.Config.ARGB_8888)
        val pixels = IntArray(w * h)
        for (y in 0 until h) {
            for (x in 0 until w) {
                val checker = ((x / 32) + (y / 32)) and 1
                val r = x * 255 / w
                val g = y * 255 / h
                val b = if (checker == 1) 200 else 60
                pixels[y * w + x] = (0xFF shl 24) or (r shl 16) or (g shl 8) or b
            }
        }
        bmp.setPixels(pixels, 0, w, 0, 0, w, h)
        bitmap = bmp

        // Person-sized hole + a thin cable stroke: both shapes matter.
        val m = ByteArray(w * h)
        for (y in 300 until 760) {
            for (x in 520 until 740) m[y * w + x] = 255.toByte()
        }
        for (x in 80 until 1200) {
            for (y in 100 until 106) m[y * w + x] = 255.toByte()
        }
        mask = m
        maskW = w
        maskH = h
        append("fixture ${w}x$h loaded (edge-heavy pattern, 2 masks)")
    }

    private fun append(line: String) {
        log.append(if (line.isEmpty()) "\n" else "$line\n")
    }
}
